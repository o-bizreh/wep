import { Router, Request, Response } from 'express';
import { randomUUID } from 'crypto';
import {
  type DynamoDBDocumentClient,
  QueryCommand,
  PutCommand,
  DeleteCommand,
  GetCommand,
} from '@wep/aws-clients';
import { getTableName } from '@wep/aws-clients';

// ─── Domain Types ─────────────────────────────────────────────────────────────

interface ChangelogEntry {
  id: string;
  teamId: string;
  teamName: string;
  type: 'deployment' | 'release' | 'incident_resolved' | 'manual';
  title: string;
  description?: string;
  serviceNames: string[];
  environment?: 'development' | 'staging' | 'production';
  author?: string;
  authorName?: string;
  linkedUrl?: string;
  tags: string[];
  createdAt: string;
  weekStart: string;
}

interface WeeklyDigest {
  teamId: string;
  teamName: string;
  weekStart: string;
  weekEnd: string;
  entryCount: number;
  deploymentCount: number;
  releaseCount: number;
  incidentCount: number;
  highlightEntry?: ChangelogEntry;
  publishedToSlack: boolean;
  publishedAt?: string;
}

// ─── DynamoDB item shapes ─────────────────────────────────────────────────────

interface EntryItem extends ChangelogEntry {
  PK: string; // TEAM#<teamId>
  SK: string; // ENTRY#<createdAt>#<id>
  GSI1PK: string; // WEEK#<weekStart>
  GSI1SK: string; // TEAM#<teamId>#ENTRY#<createdAt>#<id>
}

interface DigestItem extends WeeklyDigest {
  PK: string; // DIGEST#<teamId>
  SK: string; // WEEK#<isoWeekStart>
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

function problemDetails(status: number, title: string, detail: string) {
  return { type: 'about:blank', title, status, detail };
}

/** Returns the ISO date string of Monday of the week containing the given date. */
function getMondayOfWeek(date: Date): string {
  const d = new Date(date);
  const day = d.getUTCDay(); // 0=Sun, 1=Mon, ...
  const diff = day === 0 ? -6 : 1 - day;
  d.setUTCDate(d.getUTCDate() + diff);
  return d.toISOString().slice(0, 10);
}

function getSundayOfWeek(mondayIso: string): string {
  const d = new Date(`${mondayIso}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + 6);
  return d.toISOString().slice(0, 10);
}

function isValidEntryType(value: unknown): value is ChangelogEntry['type'] {
  return value === 'deployment' || value === 'release' || value === 'incident_resolved' || value === 'manual';
}

function isValidEnvironment(value: unknown): value is ChangelogEntry['environment'] {
  return value === 'development' || value === 'staging' || value === 'production';
}

function itemToEntry(item: EntryItem): ChangelogEntry {
  const { PK: _pk, SK: _sk, GSI1PK: _g1, GSI1SK: _g2, ...entry } = item;
  return entry;
}

function itemToDigest(item: DigestItem): WeeklyDigest {
  const { PK: _pk, SK: _sk, ...digest } = item;
  return digest;
}

// ─── Slack Block Kit message ──────────────────────────────────────────────────

function buildSlackMessage(
  teamName: string,
  weekStart: string,
  entries: ChangelogEntry[],
): unknown {
  const weekLabel = new Date(`${weekStart}T00:00:00Z`).toLocaleDateString('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
    timeZone: 'UTC',
  });

  const deployments = entries.filter((e) => e.type === 'deployment');
  const releases = entries.filter((e) => e.type === 'release');
  const incidents = entries.filter((e) => e.type === 'incident_resolved');
  const manual = entries.filter((e) => e.type === 'manual');

  const blocks: unknown[] = [
    {
      type: 'header',
      text: {
        type: 'plain_text',
        text: `📋 Team Changelog — ${teamName} · Week of ${weekLabel}`,
        emoji: true,
      },
    },
    { type: 'divider' },
  ];

  function addSection(label: string, icon: string, items: ChangelogEntry[]) {
    if (items.length === 0) return;
    blocks.push({
      type: 'section',
      text: {
        type: 'mrkdwn',
        text: `*${icon} ${label}*\n${items.map((e) => `• ${e.title}${e.serviceNames.length ? ` _(${e.serviceNames.join(', ')})_` : ''}`).join('\n')}`,
      },
    });
  }

  addSection('Deployments', '🚀', deployments);
  addSection('Releases', '🏷️', releases);
  addSection('Incidents Resolved', '🛡️', incidents);
  addSection('Manual Notes', '📝', manual);

  blocks.push({
    type: 'context',
    elements: [
      {
        type: 'mrkdwn',
        text: `Generated by WEP • ${entries.length} entries this week`,
      },
    ],
  });

  return { blocks };
}

// ─── Router ───────────────────────────────────────────────────────────────────

export function createChangelogRouter(dynamoClient: DynamoDBDocumentClient): Router {
  const router = Router();
  const tableName = getTableName('changelog');

  // GET /teams — list all team IDs that have changelog entries
  router.get('/teams', async (_req: Request, res: Response) => {
    // Query using GSI1 would require a scan; instead we scan for unique TEAM# PKs.
    // For a bounded dataset, a full table scan with a PK filter is acceptable.
    const teamIds = new Set<string>();
    let lastKey: Record<string, unknown> | undefined;

    do {
      const result = await dynamoClient.send(
        new QueryCommand({
          TableName: tableName,
          IndexName: 'GSI1',
          KeyConditionExpression: 'GSI1PK = :prefix',
          ExpressionAttributeValues: { ':prefix': 'ALL_TEAMS' },
          ExclusiveStartKey: lastKey,
          Limit: 500,
        }),
      ).catch(() => ({ Items: [] as unknown[], LastEvaluatedKey: undefined }));

      for (const item of (result.Items ?? []) as EntryItem[]) {
        teamIds.add(item.teamId);
      }
      lastKey = result.LastEvaluatedKey as Record<string, unknown> | undefined;
    } while (lastKey);

    // If GSI yields nothing (unlikely but safe), also do a lightweight scan
    if (teamIds.size === 0) {
      const scanResult = await dynamoClient.send(
        new QueryCommand({
          TableName: tableName,
          KeyConditionExpression: 'PK = :digest',
          ExpressionAttributeValues: { ':digest': 'DIGEST' },
          Limit: 500,
        }),
      ).catch(() => ({ Items: [] as unknown[] }));
      for (const item of (scanResult.Items ?? []) as DigestItem[]) {
        if (item.teamId) teamIds.add(item.teamId);
      }
    }

    res.json({ teams: Array.from(teamIds) });
  });

  // GET /teams/:teamId/entries
  router.get('/teams/:teamId/entries', async (req: Request<{ teamId: string }>, res: Response) => {
    const { teamId } = req.params;
    const { week } = req.query;

    const pk = `TEAM#${teamId}`;
    const entries: ChangelogEntry[] = [];
    let lastKey: Record<string, unknown> | undefined;

    do {
      const result = await dynamoClient.send(
        new QueryCommand({
          TableName: tableName,
          KeyConditionExpression: week
            ? 'PK = :pk AND begins_with(SK, :prefix)'
            : 'PK = :pk AND begins_with(SK, :prefix)',
          ExpressionAttributeValues: {
            ':pk': pk,
            ':prefix': 'ENTRY#',
          },
          ScanIndexForward: false,
          ExclusiveStartKey: lastKey,
        }),
      );

      for (const item of (result.Items ?? []) as EntryItem[]) {
        if (week && typeof week === 'string' && item.weekStart !== week) continue;
        entries.push(itemToEntry(item));
      }
      lastKey = result.LastEvaluatedKey as Record<string, unknown> | undefined;
    } while (lastKey);

    res.json(entries);
  });

  // GET /teams/:teamId/weeks
  router.get('/teams/:teamId/weeks', async (req: Request<{ teamId: string }>, res: Response) => {
    const { teamId } = req.params;
    const pk = `DIGEST#${teamId}`;

    const digests: WeeklyDigest[] = [];
    let lastKey: Record<string, unknown> | undefined;

    do {
      const result = await dynamoClient.send(
        new QueryCommand({
          TableName: tableName,
          KeyConditionExpression: 'PK = :pk AND begins_with(SK, :prefix)',
          ExpressionAttributeValues: { ':pk': pk, ':prefix': 'WEEK#' },
          ScanIndexForward: false,
          ExclusiveStartKey: lastKey,
        }),
      );

      for (const item of (result.Items ?? []) as DigestItem[]) {
        digests.push(itemToDigest(item));
      }
      lastKey = result.LastEvaluatedKey as Record<string, unknown> | undefined;
    } while (lastKey);

    res.json(digests);
  });

  // POST /teams/:teamId/entries
  router.post('/teams/:teamId/entries', async (req: Request<{ teamId: string }>, res: Response) => {
    const { teamId } = req.params;
    const body = req.body as Partial<ChangelogEntry>;

    if (!body.teamName || typeof body.teamName !== 'string') {
      res.status(400).json(problemDetails(400, 'Bad Request', 'teamName is required'));
      return;
    }
    if (!isValidEntryType(body.type)) {
      res.status(400).json(problemDetails(400, 'Bad Request', 'type must be deployment, release, incident_resolved, or manual'));
      return;
    }
    if (!body.title || typeof body.title !== 'string') {
      res.status(400).json(problemDetails(400, 'Bad Request', 'title is required'));
      return;
    }

    const now = new Date().toISOString();
    const weekStart = getMondayOfWeek(new Date());
    const id = randomUUID();

    const entry: ChangelogEntry = {
      id,
      teamId,
      teamName: body.teamName,
      type: body.type,
      title: body.title.trim(),
      description: body.description,
      serviceNames: Array.isArray(body.serviceNames) ? body.serviceNames : [],
      environment: isValidEnvironment(body.environment) ? body.environment : undefined,
      author: body.author,
      authorName: body.authorName,
      linkedUrl: body.linkedUrl,
      tags: Array.isArray(body.tags) ? body.tags : [],
      createdAt: now,
      weekStart,
    };

    const item: EntryItem = {
      ...entry,
      PK: `TEAM#${teamId}`,
      SK: `ENTRY#${now}#${id}`,
      GSI1PK: 'ALL_TEAMS',
      GSI1SK: `TEAM#${teamId}#ENTRY#${now}#${id}`,
    };

    await dynamoClient.send(new PutCommand({ TableName: tableName, Item: item }));

    // Upsert digest
    await upsertDigest(dynamoClient, tableName, teamId, entry.teamName, weekStart, entry);

    res.status(201).json(entry);
  });

  // DELETE /teams/:teamId/entries/:id
  router.delete('/teams/:teamId/entries/:id', async (req: Request<{ teamId: string; id: string }>, res: Response) => {
    const { teamId, id } = req.params;
    const pk = `TEAM#${teamId}`;

    // Find the SK by querying entries for this team and matching id
    const result = await dynamoClient.send(
      new QueryCommand({
        TableName: tableName,
        KeyConditionExpression: 'PK = :pk AND begins_with(SK, :prefix)',
        FilterExpression: 'id = :id',
        ExpressionAttributeValues: { ':pk': pk, ':prefix': 'ENTRY#', ':id': id },
        Limit: 10,
      }),
    );

    const item = (result.Items ?? [])[0] as EntryItem | undefined;
    if (!item) {
      res.status(404).json(problemDetails(404, 'Not Found', `Entry ${id} not found`));
      return;
    }

    await dynamoClient.send(
      new DeleteCommand({ TableName: tableName, Key: { PK: item.PK, SK: item.SK } }),
    );

    res.status(204).send();
  });

  // POST /teams/:teamId/publish-week
  router.post('/teams/:teamId/publish-week', async (req: Request<{ teamId: string }>, res: Response) => {
    const { teamId } = req.params;
    const { weekStart } = req.body as { weekStart?: string };

    if (!weekStart || typeof weekStart !== 'string') {
      res.status(400).json(problemDetails(400, 'Bad Request', 'weekStart is required'));
      return;
    }

    // Load all entries for this week
    const pk = `TEAM#${teamId}`;
    const entries: ChangelogEntry[] = [];
    let lastKey: Record<string, unknown> | undefined;

    do {
      const result = await dynamoClient.send(
        new QueryCommand({
          TableName: tableName,
          KeyConditionExpression: 'PK = :pk AND begins_with(SK, :prefix)',
          ExpressionAttributeValues: { ':pk': pk, ':prefix': 'ENTRY#' },
          ScanIndexForward: false,
          ExclusiveStartKey: lastKey,
        }),
      );
      for (const item of (result.Items ?? []) as EntryItem[]) {
        if (item.weekStart === weekStart) entries.push(itemToEntry(item));
      }
      lastKey = result.LastEvaluatedKey as Record<string, unknown> | undefined;
    } while (lastKey);

    if (entries.length === 0) {
      res.status(422).json(problemDetails(422, 'Unprocessable Entity', 'No entries found for this week'));
      return;
    }

    const teamName = entries[0]?.teamName ?? teamId;
    const slackMessage = buildSlackMessage(teamName, weekStart, entries);

    // Post to Slack
    const webhookUrl = process.env['SLACK_UPDATES_WEBHOOK'] ?? process.env['SLACK_WEBHOOK_URL'];
    const channel = process.env['SLACK_UPDATES_CHANNEL'] ?? '#engineering-updates';

    if (webhookUrl) {
      try {
        await fetch(webhookUrl, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ ...slackMessage as object, channel }),
        });
      } catch (err) {
        console.error('[changelog publish-week] Slack post failed:', err);
        // Non-fatal — still mark as published
      }
    } else {
      console.warn('[changelog publish-week] SLACK_UPDATES_WEBHOOK not set; skipping Slack post');
    }

    // Mark digest as published
    const digestPk = `DIGEST#${teamId}`;
    const digestSk = `WEEK#${weekStart}`;
    const existingDigest = await dynamoClient.send(
      new GetCommand({ TableName: tableName, Key: { PK: digestPk, SK: digestSk } }),
    );

    const weekEnd = getSundayOfWeek(weekStart);
    const deploymentCount = entries.filter((e) => e.type === 'deployment').length;
    const releaseCount = entries.filter((e) => e.type === 'release').length;
    const incidentCount = entries.filter((e) => e.type === 'incident_resolved').length;

    const digest: DigestItem = {
      ...((existingDigest.Item as DigestItem | undefined) ?? {
        teamId,
        teamName,
        weekStart,
        weekEnd,
        entryCount: entries.length,
        deploymentCount,
        releaseCount,
        incidentCount,
        publishedToSlack: false,
      }),
      PK: digestPk,
      SK: digestSk,
      publishedToSlack: true,
      publishedAt: new Date().toISOString(),
    };

    await dynamoClient.send(new PutCommand({ TableName: tableName, Item: digest }));

    res.json({ ok: true, publishedAt: digest.publishedAt, channel });
  });

  // GET /summary
  router.get('/summary', async (_req: Request, res: Response) => {
    const weekStart = getMondayOfWeek(new Date());

    // Fetch entries from this week across all teams via GSI
    const entries: ChangelogEntry[] = [];
    let lastKey: Record<string, unknown> | undefined;

    do {
      const result = await dynamoClient.send(
        new QueryCommand({
          TableName: tableName,
          IndexName: 'GSI1',
          KeyConditionExpression: 'GSI1PK = :pk',
          ExpressionAttributeValues: { ':pk': 'ALL_TEAMS' },
          ExclusiveStartKey: lastKey,
          Limit: 1000,
        }),
      ).catch(() => ({ Items: [] as unknown[], LastEvaluatedKey: undefined }));

      for (const item of (result.Items ?? []) as EntryItem[]) {
        if (item.weekStart === weekStart) entries.push(itemToEntry(item));
      }
      lastKey = result.LastEvaluatedKey as Record<string, unknown> | undefined;
    } while (lastKey);

    const totalEntries = entries.length;
    const totalDeployments = entries.filter((e) => e.type === 'deployment').length;

    // Most active team
    const teamCounts = new Map<string, { teamId: string; teamName: string; count: number }>();
    for (const e of entries) {
      const existing = teamCounts.get(e.teamId);
      if (existing) {
        existing.count++;
      } else {
        teamCounts.set(e.teamId, { teamId: e.teamId, teamName: e.teamName, count: 1 });
      }
    }

    let mostActiveTeam: { teamId: string; teamName: string; count: number } | null = null;
    for (const tc of teamCounts.values()) {
      if (!mostActiveTeam || tc.count > mostActiveTeam.count) mostActiveTeam = tc;
    }

    res.json({
      weekStart,
      totalEntriesThisWeek: totalEntries,
      totalDeploymentsThisWeek: totalDeployments,
      mostActiveTeam,
    });
  });

  return router;
}

// ─── Digest upsert helper ─────────────────────────────────────────────────────

async function upsertDigest(
  dynamoClient: DynamoDBDocumentClient,
  tableName: string,
  teamId: string,
  teamName: string,
  weekStart: string,
  newEntry: ChangelogEntry,
): Promise<void> {
  const pk = `DIGEST#${teamId}`;
  const sk = `WEEK#${weekStart}`;

  const existing = await dynamoClient.send(
    new GetCommand({ TableName: tableName, Key: { PK: pk, SK: sk } }),
  );

  const weekEnd = getSundayOfWeek(weekStart);
  const current = existing.Item as DigestItem | undefined;

  const deploymentCount = (current?.deploymentCount ?? 0) + (newEntry.type === 'deployment' ? 1 : 0);
  const releaseCount = (current?.releaseCount ?? 0) + (newEntry.type === 'release' ? 1 : 0);
  const incidentCount = (current?.incidentCount ?? 0) + (newEntry.type === 'incident_resolved' ? 1 : 0);
  const entryCount = (current?.entryCount ?? 0) + 1;

  const digest: DigestItem = {
    PK: pk,
    SK: sk,
    teamId,
    teamName,
    weekStart,
    weekEnd,
    entryCount,
    deploymentCount,
    releaseCount,
    incidentCount,
    highlightEntry: current?.highlightEntry ?? newEntry,
    publishedToSlack: current?.publishedToSlack ?? false,
    publishedAt: current?.publishedAt,
  };

  await dynamoClient.send(new PutCommand({ TableName: tableName, Item: digest }));
}
